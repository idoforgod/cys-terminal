#!/usr/bin/env python3
"""
Generate src/pack_prev_vendor.rs - the built-in table of PREVIOUS-RELEASE vendor content hashes
that the C-07 stale-entry migration uses as its authority.

★WHY A COMMITTED GENERATED FILE, NOT A BUILD STEP (measured, 0.14.55-P3-DESIGN-R2 section 2-2):
   .github/workflows/release.yml checks out at three places with NO fetch-depth and no fetch-tags,
   i.e. the DEFAULT depth 1 - a shallow clone with no tags and no history. The release build
   therefore cannot read `git show v0.14.x:cysjavis-pack/<rel>` at all. Only ci-branch.yml (one job)
   and windows-health.yml set fetch-depth: 0. So the table is generated by a maintainer with full
   history, committed, and merely compiled in; a CI freshness check belongs in a fetch-depth 0 job.
   ★0.15.0 (「스스로 해결」 M11 다 · CONTRACTS O-C8-5 (i)): that check is the ci-branch.yml job
   `prev-vendor-freshness` (actions/checkout fetch-depth: 0 = every branch and tag) running
   `--check`. The tag lane does not run it (release.yml is not changed).

WINDOW (decision item 2, widened in 0.15.0 - design §4-11 다 "0.14.x 밖으로 넓히고"): every release
   tag `vX.Y.Z` or `pack-vX.Y.Z` with X.Y.Z >= 0.14.0 that resolves to a commit at generation time,
   EXCEPT a tag that points at HEAD itself (that is the release being built, not a previous one -
   excluding it keeps `--check` stable when the release tag is pushed on the checked commit).
   Before 0.15.0 the window was `v0.14.*` only, so a 0.15.x release would never have entered it.
   Tags older than 0.14.0 stay out (unchanged decision). `pack-v` tags are included because a
   pack-only release ships vendor bytes too (none >= 0.14.0 exists when this was written).
HASH: sha256 of the blob content == pack.rs content_hash(), which is what .install-manifest.json holds.
PREDICATE for the path set: build.rs:48-65 - git-tracked files under cysjavis-pack/, prefix
stripped, EXCLUDING any path component starting with '.' or equal to 'tests'/'__pycache__'.

Usage:  python3 scripts/gen_prev_vendor_hashes.py [--check]
        --check exits 1 if the committed table's ROWS (the generated code) or its WINDOW floor differ from
        what this generator would produce now. The informational header lines (tag count and range, path
        counts, the absent list, the provenance line) are NOT compared (RULINGS AE1): after every new
        release tag they change although no hash row does, and a branch push must not turn red for that.
Exit:   0 = written / FRESH · 1 = STALE · 2 = REFUSED (shallow clone, no release tag, git failure)
        - a run that cannot see the window is never reported as fresh.
"""
import subprocess, sys, hashlib, os, pathlib, re, difflib

REPO = pathlib.Path(__file__).resolve().parent.parent
OUT = REPO / 'src' / 'pack_prev_vendor.rs'

# release tag names: `v1.2.3` (binary + pack release) and `pack-v1.2.3` (pack-only release)
TAG_RE = re.compile(r'^(v|pack-v)(\d+)\.(\d+)\.(\d+)$')
WINDOW_FLOOR = (0, 14, 0)
EXIT_REFUSED = 2


def refuse(msg):
    print(f'REFUSED: {msg}', file=sys.stderr)
    raise SystemExit(EXIT_REFUSED)


def git(*a, binary=False):
    r = subprocess.run(['git', '-C', str(REPO), *a], capture_output=True)
    if r.returncode != 0:
        refuse(f'git {" ".join(a)}: {r.stderr.decode()[:200]}')
    return r.stdout if binary else r.stdout.decode('utf-8', 'replace')

def pack_all_at(rev):
    """{rel: blob_oid} under the build.rs predicate."""
    out = {}
    for ln in git('ls-tree', '-r', rev, '--', 'cysjavis-pack/').split('\n'):
        if not ln.strip():
            continue
        meta, path = ln.split('\t', 1)
        _mode, typ, oid = meta.split()
        if typ != 'blob' or not path.startswith('cysjavis-pack/'):
            continue
        rel = path[len('cysjavis-pack/'):]
        if any(c.startswith('.') or c in ('tests', '__pycache__') for c in rel.split('/')):
            continue
        out[rel] = oid
    return out

def release_tags(head):
    """The window: resolvable release tags >= WINDOW_FLOOR, sorted by version (`v` before `pack-v`),
    without a tag whose commit is HEAD."""
    found = []
    for t in git('tag', '--list').split('\n'):
        t = t.strip()
        m = TAG_RE.match(t)
        if not m:
            continue
        ver = tuple(int(x) for x in m.group(2, 3, 4))
        if ver < WINDOW_FLOOR:
            continue
        r = subprocess.run(['git', '-C', str(REPO), 'rev-parse', '--verify', '--quiet', f'{t}^{{commit}}'],
                           capture_output=True)
        if r.returncode != 0:
            continue
        if r.stdout.decode('utf-8', 'replace').strip() == head:
            continue
        found.append((ver, 0 if m.group(1) == 'v' else 1, t))
    found.sort()
    return [t for _v, _k, t in found]

def compared_part(text):
    """What `--check` compares (RULINGS AE1): (the window floor stated on the WINDOW line, the generated code
    from the first non-comment line on — the PREV_VENDOR_HASHES rows and the lookup function)."""
    lines = text.split('\n')
    floor = None
    for l in lines:
        if l.startswith('// WINDOW'):
            m = re.search(r'>= (\d+\.\d+\.\d+)', l)
            floor = m.group(1) if m else None
            break
    start = next((i for i, l in enumerate(lines) if l.strip() and not l.startswith('//')), len(lines))
    return floor, '\n'.join(lines[start:])

def main():
    check = '--check' in sys.argv
    if git('rev-parse', '--is-shallow-repository').strip() == 'true':
        refuse('shallow clone - the window needs every release tag and its tree; '
               'check out with full history (actions/checkout `fetch-depth: 0`)')
    head = git('rev-parse', 'HEAD').strip()
    tags = release_tags(head)
    if not tags:
        refuse('no release tag (v*/pack-v* >= %d.%d.%d) resolves in this repository - tags not fetched? '
               '(actions/checkout `fetch-depth: 0` fetches them)' % WINDOW_FLOOR)

    now = pack_all_at(head)
    trees = {t: pack_all_at(t) for t in tags}
    oid_sha = {}                     # blob oid -> sha256 of its content (computed once per oid)

    def sha_of(oid):
        if oid not in oid_sha:
            oid_sha[oid] = hashlib.sha256(git('cat-file', 'blob', oid, binary=True)).hexdigest()
        return oid_sha[oid]

    rows, unchanged, absent = {}, [], []
    for rel, oid_now in sorted(now.items()):
        prior, appeared = [], 0
        for t in tags:
            o = trees[t].get(rel)
            if o is None:
                continue
            appeared += 1
            if o != oid_now:
                h = sha_of(o)
                if h not in prior:
                    prior.append(h)
        if appeared == 0:
            absent.append(rel)
        elif prior:
            rows[rel] = prior
        else:
            unchanged.append(rel)
    assert len(rows) + len(unchanged) + len(absent) == len(now), 'census does not reconcile'

    L = []
    L.append('// @generated by scripts/gen_prev_vendor_hashes.py - DO NOT EDIT BY HAND.')
    L.append('//')
    L.append('// C-07 (0.14.55 - P3): the AUTHORITY for "these disk bytes are a previous vendor\'s bytes".')
    L.append('// A table of PREVIOUS-RELEASE vendor content hashes, carried INSIDE the release. `.pristine`')
    L.append('// equality is a corroborating signal only and is never sufficient on its own - `.pristine` is')
    L.append('// written by the installer whose index is the thing that went stale, so it cannot be the')
    L.append('// authority for its own correctness.')
    L.append('//')
    L.append('// WHY COMMITTED AND NOT GENERATED AT BUILD TIME (measured): release.yml checks out at depth 1')
    L.append('// with no tags, so the release build cannot read previous release tags at all. The freshness')
    L.append('// check is the ci-branch.yml job `prev-vendor-freshness` (fetch-depth: 0, `--check`).')
    L.append('//')
    floor = '%d.%d.%d' % WINDOW_FLOOR
    L.append(f'// WINDOW         : {len(tags)} resolvable release tags (v*/pack-v* >= {floor}, not HEAD\'s own), '
             f'{tags[0]} .. {tags[-1]}')
    L.append(f'// PACK_ALL paths : {len(now)}   (build.rs:48-65 predicate)')
    L.append(f'// with a row     : {len(rows)}')
    L.append(f'// unchanged      : {len(unchanged)}   (identical in every tag they appeared in -> no row needed:')
    L.append('//                  an unedited copy already equals the embed and Arm 1 matches before the table)')
    L.append(f'// absent         : {len(absent)}   (new in this release - no previous vendor content exists)')
    if absent:
        for r in absent:
            L.append(f'//   + {r}')
    L.append(f'// generated from : {head}')
    L.append('')
    L.append('/// `(rel, &[sha256 of that path\'s content in each prior release where it differed])`.')
    L.append('/// Sorted by `rel`; [`prev_vendor_hashes`] relies on that for a binary search.')
    L.append('pub static PREV_VENDOR_HASHES: &[(&str, &[&str])] = &[')
    for rel in sorted(rows):
        hs = ', '.join(f'"{h}"' for h in rows[rel])
        L.append(f'    ("{rel}", &[{hs}]),')
    L.append('];')
    L.append('')
    L.append('/// The prior-release hashes recorded for `rel`, or an empty slice when the path has no row')
    L.append('/// (new path, or unchanged across the whole window). An empty slice is the NO-ROW case and')
    L.append('/// the migration must repair nothing and report - never guess.')
    L.append('pub fn prev_vendor_hashes(rel: &str) -> &\'static [&\'static str] {')
    L.append('    match PREV_VENDOR_HASHES.binary_search_by(|(r, _)| (*r).cmp(rel)) {')
    L.append('        Ok(i) => PREV_VENDOR_HASHES[i].1,')
    L.append('        Err(_) => &[],')
    L.append('    }')
    L.append('}')
    text = '\n'.join(L) + '\n'

    if check:
        cur = OUT.read_text(encoding='utf-8') if OUT.exists() else ''
        (cur_floor, cur_code), (new_floor, new_code) = compared_part(cur), compared_part(text)
        if cur_floor != new_floor or cur_code != new_code:
            print('STALE: src/pack_prev_vendor.rs is not what the generator produces now '
                  '(regenerate: python3 scripts/gen_prev_vendor_hashes.py, then commit)')
            if cur_floor != new_floor:
                print(f'  window floor: committed {cur_floor or "(none)"} · generator {new_floor}')
            diff = list(difflib.unified_diff(cur_code.split('\n'), new_code.split('\n'),
                                             'committed', 'generated now', n=0, lineterm=''))
            for line in diff[:24]:
                print('  ' + (line if len(line) <= 200 else line[:200] + ' …'))
            if len(diff) > 24:
                print(f'  … {len(diff) - 24} more diff lines')
            return 1
        print(f'FRESH: {len(rows)} rows over {len(tags)} tags, {len(now)} paths')
        return 0
    OUT.write_text(text, encoding='utf-8')
    print(f'wrote {OUT.relative_to(REPO)}: {len(rows)} rows / {len(unchanged)} unchanged / '
          f'{len(absent)} absent over {len(tags)} tags ({len(now)} paths)')
    return 0

sys.exit(main())
