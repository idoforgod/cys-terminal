#!/usr/bin/env python3
"""
Generate src/pack_prev_vendor.rs - the built-in table of PREVIOUS-RELEASE vendor content hashes
that the C-07 stale-entry migration uses as its authority.

★WHY A COMMITTED GENERATED FILE, NOT A BUILD STEP (measured, 0.14.55-P3-DESIGN-R2 section 2-2):
   .github/workflows/release.yml checks out at three places with NO fetch-depth and no fetch-tags,
   i.e. the DEFAULT depth 1 - a shallow clone with no tags and no history. The release build
   therefore cannot read `git show v0.14.x:cysjavis-pack/<rel>` at all. Only ci-branch.yml (one job)
   and windows-health.yml set fetch-depth: 0. So the table is generated by a maintainer with full
   history, committed, and merely compiled in; a CI freshness check belongs in a fetch-depth 0 job.

WINDOW (decision item 2): every v0.14.* tag that resolves in the repository at generation time.
HASH: sha256 of the blob content == pack.rs content_hash(), which is what .install-manifest.json holds.
PREDICATE for the path set: build.rs:48-65 - git-tracked files under cysjavis-pack/, prefix
stripped, EXCLUDING any path component starting with '.' or equal to 'tests'/'__pycache__'.

Usage:  python3 scripts/gen_prev_vendor_hashes.py [--check]
        --check exits 1 if the committed file is not what this generator would produce now.
"""
import subprocess, sys, hashlib, os, pathlib

REPO = pathlib.Path(__file__).resolve().parent.parent
OUT = REPO / 'src' / 'pack_prev_vendor.rs'

def git(*a, binary=False):
    r = subprocess.run(['git', '-C', str(REPO), *a], capture_output=True)
    if r.returncode != 0:
        raise SystemExit(f'git {" ".join(a)}: {r.stderr.decode()[:200]}')
    return r.stdout if binary else r.stdout.decode('utf-8', 'replace')

def pack_all_at(rev):
    """{rel: blob_oid} under the build.rs predicate."""
    out = {}
    for ln in git('ls-tree', '-r', rev, '--', 'cysjavis-pack/').split('\n'):
        if not ln.strip():
            continue
        meta, path = ln.split('\t', 1)
        _mode, typ, oid = meta.split()
        if typ != 'blob' or not path.startswith('cysjavis-pack/'):
            continue
        rel = path[len('cysjavis-pack/'):]
        if any(c.startswith('.') or c in ('tests', '__pycache__') for c in rel.split('/')):
            continue
        out[rel] = oid
    return out

def main():
    check = '--check' in sys.argv
    head = git('rev-parse', 'HEAD').strip()
    tags = [t for t in git('tag', '--list', 'v0.14.*').split('\n') if t.strip()]
    tags = [t for t in tags
            if subprocess.run(['git', '-C', str(REPO), 'rev-parse', '--verify', f'{t}^{{commit}}'],
                              capture_output=True).returncode == 0]
    tags.sort(key=lambda t: [int(x) for x in t[1:].split('.') if x.isdigit()] or [0])

    now = pack_all_at(head)
    trees = {t: pack_all_at(t) for t in tags}
    oid_sha = {}                     # blob oid -> sha256 of its content (computed once per oid)

    def sha_of(oid):
        if oid not in oid_sha:
            oid_sha[oid] = hashlib.sha256(git('cat-file', 'blob', oid, binary=True)).hexdigest()
        return oid_sha[oid]

    rows, unchanged, absent = {}, [], []
    for rel, oid_now in sorted(now.items()):
        prior, appeared = [], 0
        for t in tags:
            o = trees[t].get(rel)
            if o is None:
                continue
            appeared += 1
            if o != oid_now:
                h = sha_of(o)
                if h not in prior:
                    prior.append(h)
        if appeared == 0:
            absent.append(rel)
        elif prior:
            rows[rel] = prior
        else:
            unchanged.append(rel)
    assert len(rows) + len(unchanged) + len(absent) == len(now), 'census does not reconcile'

    L = []
    L.append('// @generated by scripts/gen_prev_vendor_hashes.py - DO NOT EDIT BY HAND.')
    L.append('//')
    L.append('// C-07 (0.14.55 - P3): the AUTHORITY for "these disk bytes are a previous vendor\'s bytes".')
    L.append('// A table of PREVIOUS-RELEASE vendor content hashes, carried INSIDE the release. `.pristine`')
    L.append('// equality is a corroborating signal only and is never sufficient on its own - `.pristine` is')
    L.append('// written by the installer whose index is the thing that went stale, so it cannot be the')
    L.append('// authority for its own correctness.')
    L.append('//')
    L.append('// WHY COMMITTED AND NOT GENERATED AT BUILD TIME (measured): release.yml checks out at depth 1')
    L.append('// with no tags, so the release build cannot read previous release tags at all. A freshness')
    L.append('// check belongs in a fetch-depth: 0 job (ci-branch.yml has one).')
    L.append('//')
    L.append(f'// WINDOW         : {len(tags)} resolvable v0.14.* tags, {tags[0]} .. {tags[-1]}')
    L.append(f'// PACK_ALL paths : {len(now)}   (build.rs:48-65 predicate)')
    L.append(f'// with a row     : {len(rows)}')
    L.append(f'// unchanged      : {len(unchanged)}   (identical in every tag they appeared in -> no row needed:')
    L.append('//                  an unedited copy already equals the embed and Arm 1 matches before the table)')
    L.append(f'// absent         : {len(absent)}   (new in this release - no previous vendor content exists)')
    if absent:
        for r in absent:
            L.append(f'//   + {r}')
    L.append(f'// generated from : {head}')
    L.append('')
    L.append('/// `(rel, &[sha256 of that path\'s content in each prior release where it differed])`.')
    L.append('/// Sorted by `rel`; [`prev_vendor_hashes`] relies on that for a binary search.')
    L.append('pub static PREV_VENDOR_HASHES: &[(&str, &[&str])] = &[')
    for rel in sorted(rows):
        hs = ', '.join(f'"{h}"' for h in rows[rel])
        L.append(f'    ("{rel}", &[{hs}]),')
    L.append('];')
    L.append('')
    L.append('/// The prior-release hashes recorded for `rel`, or an empty slice when the path has no row')
    L.append('/// (new path, or unchanged across the whole window). An empty slice is the NO-ROW case and')
    L.append('/// the migration must repair nothing and report - never guess.')
    L.append('pub fn prev_vendor_hashes(rel: &str) -> &\'static [&\'static str] {')
    L.append('    match PREV_VENDOR_HASHES.binary_search_by(|(r, _)| (*r).cmp(rel)) {')
    L.append('        Ok(i) => PREV_VENDOR_HASHES[i].1,')
    L.append('        Err(_) => &[],')
    L.append('    }')
    L.append('}')
    text = '\n'.join(L) + '\n'

    if check:
        cur = OUT.read_text(encoding='utf-8') if OUT.exists() else ''
        # the provenance line moves with HEAD, so compare everything except it
        strip = lambda t: '\n'.join(l for l in t.split('\n') if not l.startswith('// generated from'))
        if strip(cur) != strip(text):
            print('STALE: src/pack_prev_vendor.rs is not what the generator produces now')
            return 1
        print(f'FRESH: {len(rows)} rows over {len(tags)} tags, {len(now)} paths')
        return 0
    OUT.write_text(text, encoding='utf-8')
    print(f'wrote {OUT.relative_to(REPO)}: {len(rows)} rows / {len(unchanged)} unchanged / '
          f'{len(absent)} absent over {len(tags)} tags ({len(now)} paths)')
    return 0

sys.exit(main())
