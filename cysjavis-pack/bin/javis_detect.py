#   용례 미실증: 근거 없는 억제 확장 금지, 실증 발견 시 추가) · '치고'(체언 전용) · '그래'/
#   '그려'('-구먼/-군/-네' 뒤 전용 — "라고 그래"의 '그래'는 동사 '그러다'지 보조사가 아니다) ·
