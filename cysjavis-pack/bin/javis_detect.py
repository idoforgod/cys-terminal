#            띄어쓴 꼴은 종전부터 억제)이라 극성이 같다 — 회귀 아님.
#     라두 — 채택어 '라도'의 방언 변이(도→두 모음 대응 — 두·유 채택과 동계). ⓐ "라고라두 해
