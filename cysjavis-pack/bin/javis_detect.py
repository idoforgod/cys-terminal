#   ③ 부착 원리와의 정합 — 보조사는 조사에 형태적으로 **직결**된다(라고는·라고도). W-F3 이
#     세운 부착 원칙을 버리는 게 아니라 완성하는 방향이다.
# ★집합 선정 실측(후보마다 ⓐ 인용 전달 억제 성립 ⓑ 어두 실재어·정당 선언 발화 유지 — 양방향):
#   · W-F4 채택 15종 = 는·은·도·만·까지·조차·마저·부터·라도·나·야·요(티켓 최소 12종) + 방언
#     두(=도)·유(=요) + 밖에("라고밖에 안 들리네" 상용).
#   · W-F5 채택 +5종(master 실측 누수 + 리뷰어 지목분 — 각각 ⓐⓑ probe 재실측):
#     들   — 복수 보조사(표준국어대사전 「들」 조사: 체언·부사어·연결어미 '-아/-게/-지/-고'·
