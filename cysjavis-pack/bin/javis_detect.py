#   미실증: 실증 시 추가) · '나마'·'야말로'·'는커녕'(각각 '나'·'야'·'는' 접두 일치가 자동
#   커버 — 별도 등재 불요).
# ★완결성(W-F5 — 성립 층위를 명시한 정직 표기 · 두 라운드 연속 "완결" 주장→반례 재발의 교훈):
#   ① 표준어 보조사 층위: **닫혔다.** 조사는 신조가 생산되지 않는 폐품사라 사전 표제어로 유한
#     열거가 가능하고(표준국어대사전 보조사 표제 — 국립국어원), 위 채택 14 표준원(는·은·도·
#     만·까지·조차·마저·부터·라도·나·야·요·밖에·들)+접두 자동 커버(나마·야말로·는커녕·겹보조사
#     일반)+기각(결합 불가 사유 각 명기)으로 표제 보조사 전수가 처분됐다. 이 층위의 미확정
#     잔여는 '일랑'·'든지' 용례 실증 대기 2건뿐이며 둘 다 비문 판정 우세라 미채택이 보수다.
#   ② 표기 변이 층위(방언 모음 대응·통신체·축약·융합): **원리적으로 닫히지 않는다.** 채택
#     변이(두·유·여·라두·밖엔·서)는 실측·리뷰어 지목분이고, 실측 FIRE 잔여가 남아 있다 —
#     애교체 "라고용"·"라고염"(요-변이 개방족) · 축약 융합 "라곤"(=라고+는: lookahead 가 아니라
#     '라고' 어휘 자체의 변형이라 이 집합 밖 = 어휘 축 잔여) · 조사 변이 "라구"(=라고 — 동일
#     사유 어휘 축 잔여) · 동사 융합 "라고그래"(무공백 채팅체 — 보조사 아님). 전부 발견·실측
#     시 개별 채택+corpus 핀으로 닫는다(선제 일괄 확장은 근거 없는 억제 = W-A2 위반).
_QUOT_AUX = r"(?:는|은|도|두|만|까지|조차|마저|부터|라도|라두|나|야|요|유|여|밖에|밖엔|들|서)"
# 캡처 계약: 부착군·일반군 각 1개의 캡처 그룹 — 매치 시 정확히 하나만 non-None 이고, 그것이
# 진단 마커다(_suppression 이 소비). 내부 그룹은 전부 비캡처를 유지할 것(_QUOT_AUX 포함).
QUOTATIVE = re.compile(
    "(?:"
    + _QGAP_STICK
    + r"(이?라고(?= {0,2}[가-힣])|면서(?=" + _QUOT_AUX + r"|$|[^가-힣]))"
    + "|" + _QGAP_ANY
    + r"(이?라고(?= {1,2}[가-힣]|" + _QUOT_AUX + r")|이?라(?:면서|는|며)|이?라니(?= {1,2}[가-힣])"
    + r"|처럼|가 ?뭐|가 무|[?？])"
    + ")")
