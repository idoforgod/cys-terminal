#     목적어 어절('답장에')이 끼는 정상 어순이라 '다음 어절=동사' 검사가 놓친다(probe 확인 —
#     누수 잔존). 어절 건너뛰기 스캔을 붙이면 '부착=문법 경계'(인접창) 원리를 버리는 구조
