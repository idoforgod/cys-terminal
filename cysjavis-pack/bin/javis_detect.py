#   된다 — 짝 어긋남을 core 로 삼은 그 근사가 정확히 과억제(무발화 앵커) 쪽으로 기울었다.
# 판정법(티켓 W-F1 채택 · 5형 실측 확정):
#   · 대칭 부호(QUOTE_SYMMETRIC — ' " ` 는 여닫이 구분이 없는 문자): 절 시작~선언 시작 구간의
#     출현 **홀짝(패리티)** 으로 열림을 판정한다. 홀수 = 마지막 부호가 미결(=여는 방향), 짝수 =
#     좌측 짝 전부 완결(인용이 선언 앞에서 끝남 = 비감쌈). 열림 + 선언 뒤 절 꼬리에 같은 부호
#     1자 = 감쌈. 한국어 채팅 따옴표는 여닫이 구분이 없는 경우가 대부분이라 방향 추정보다
#     짝 개수 기반이 견고하다.
#   · 방향 부호(QUOTE_PAIRS — ‘’ “” 「」 『』 는 여닫이가 다른 문자): 여는/닫는 **잔고 스택**으로
#     미결 여는 부호를 직접 추적한다(고아 닫음 부호는 잔고를 0 밑으로 못 내린다).
# ★정서법 아포스트로피 배제(W-F1): **양옆이 영문자**인 U+0027(')·U+2019(’)는 don't·let's·it's
#   의 철자이지 인용부호가 아니다 — 개수·잔고 어디에도 세지 않는다(_apostrophe).
# ★백틱(`) 유지 판정(W-F1 실측): 개발 채팅에서 백틱 코드 인용은 상시 어휘라 후보 제외도 검토
#   했다. 실측 결론 = **유지**: 오억제의 원인은 백틱이 아니라 '양쪽 존재' 근사였다 — 닫힌 코드
#   스팬("`cys boot` … `check`")은 패리티에서 자연 통과(짝수=발화)하고, 진짜 감쌈("`너는
#   마스터다`를 그대로 워커에게 보내" = mention)은 계속 억제해야 한다(corpus SKIP 핀). 후보에서
#   빼면 후자가 오발화한다 — 억제를 좁히는 방향의 어휘 삭제는 금지(오발화 = 폭주 앵커).
QUOTE_SYMMETRIC = "'\"`"     # 직선 따옴표 2종 + 백틱 — 패리티(홀짝) 판정
QUOTE_PAIRS = (("‘", "’"), ("“", "”"), ("「", "」"), ("『", "』"))  # 방향 부호 — 잔고 판정
# 합집합(값은 W-A2 와 동일 — 진단·호환용). 《〈 류 서명 괄호는 문장 인용 관례가 아니라서 여전히
# 제외한다(감쌈 오탐 표면 최소화).
QUOTES = QUOTE_SYMMETRIC + "".join(op + cl for op, cl in QUOTE_PAIRS)


def _flatten(text):
    """개행·탭 → 공백 **1:1 치환**(길이·오프셋 보존).

    구 훅은 `tr '\\n' ' '` 로 개행을 없앤 뒤 grep 했다. 여기서도 매칭은 평탄화 텍스트에서
    하되(선언이 줄바꿈을 걸쳐도 감지 — 구 동작 보존), **절 경계 계산은 원문**에서 한다
    (개행은 절 경계다). 두 문자열의 인덱스가 1:1로 정렬돼야 하므로 길이를 바꾸지 않는다.
    """
    return text.replace("\r", " ").replace("\n", " ").replace("\t", " ")


def _clause_bounds(raw, start, end):
    """`raw` 에서 [start,end) 매치를 **완전히 포함하는 절**의 (lo, hi) 반환.

    lo = 매치 시작 왼쪽의 가장 가까운 경계 문자 다음 / hi = 매치 끝 오른쪽의 가장 가까운
    경계 문자 **포함**(없으면 문자열 끝). 매치 전체를 감싸는 이유: filler 안에 마침표가
    들어간 병리 입력("너는. 마스터다'가 무슨 뜻?")에서 절이 매치를 갈라 억제 마커를
    놓치는 것을 막는다(fail-closed 방향).
    """
    lo = 0
    for i in range(start - 1, -1, -1):
        if raw[i] in CLAUSE_BOUNDARY:
            lo = i + 1
            break
    hi = len(raw)
    for i in range(end, len(raw)):
        if raw[i] in CLAUSE_BOUNDARY:
            hi = i + 1
            break
    return lo, hi


def _matches(flat):
    """선언 후보 전량(한국어·영문)을 시작 오프셋 순으로 반환."""
    found = [(m.start(), m.end(), m.group(0), "ko") for m in DECL_KO.finditer(flat)]
    found += [(m.start(), m.end(), m.group(0), "en") for m in DECL_EN.finditer(flat)]
    found.sort(key=lambda t: (t[0], t[1]))
    return found


def _apostrophe(flat, i):
    """flat[i] 가 정서법 아포스트로피인가 — **양옆이 영문자**인 U+0027(')·U+2019(’).

    W-F1: don't·let's·it's 의 ' 는 철자이지 인용부호가 아니다 — 축ⓑ의 개수·잔고에서 제외한다.
    ASCII 영문자로 좁힌 근거: 아포스트로피 정서법은 라틴 철자 내부에만 존재하고, 한글 인접
    따옴표("마스터다'가")는 실제 인용 용법이라 배제하면 안 된다(과배제 = 억제 축소 방향 금지).
    """
    if flat[i] not in "'’":
        return False
    return (0 < i and i + 1 < len(flat)
            and flat[i - 1].isascii() and flat[i - 1].isalpha()
            and flat[i + 1].isascii() and flat[i + 1].isalpha())


def _quote_wrap(flat, lo, hi, start, end):
    """축ⓑ 감쌈 실판정(W-F1). 감싸면 (여는 부호, 닫는 부호), 아니면 None.

    감쌈 = 절 내부 선언 좌측([lo,start))에 **아직 닫히지 않은** 여는 부호가 있고, 같은 짝의
    닫는 부호가 선언 우측 절 꼬리([end,hi))에 있다. 좌측 짝이 완결(패리티 짝수·잔고 0)이면
    그 인용은 선언 앞에서 이미 끝난 것이라 우측에 다른 짝이 또 있어도 감쌈이 아니다(발화 측).
    판정법·어휘 근거는 QUOTES 상수 블록 주석. 여러 짝이 동시에 감싸면 여는 부호가 선언에
    가장 가까운(최내곽) 짝을 진단 마커로 고른다 — 극성엔 무영향, exit 3 진단 품질용.
    """
    best = None                  # (여는 부호 위치, 여는 부호, 닫는 부호) — 위치 최대 = 최내곽
    for ch in QUOTE_SYMMETRIC:
        opens = [i for i in range(lo, start) if flat[i] == ch and not _apostrophe(flat, i)]
        if len(opens) % 2 == 1 and any(flat[i] == ch and not _apostrophe(flat, i)
                                       for i in range(end, hi)):
            if best is None or opens[-1] > best[0]:
                best = (opens[-1], ch, ch)
    for op, cl in QUOTE_PAIRS:
        pend = []                # 미결 여는 부호 위치 스택
        for i in range(lo, start):
            if flat[i] == op:
                pend.append(i)
            elif flat[i] == cl and not _apostrophe(flat, i) and pend:
                pend.pop()
        if pend and any(flat[i] == cl and not _apostrophe(flat, i) for i in range(end, hi)):
            if best is None or pend[-1] > best[0]:
                best = (pend[-1], op, cl)
    return (best[1], best[2]) if best else None


def _suppression(flat, lo, hi, start, end):
    """한 선언 후보의 억제 판정(W-A2 3축 + 부정). 반환 (axis, marker, reason) 또는 None.

    축 평가 순서 = neg → ⓐpre → ⓑquote → ⓒquotative. 순서는 진단 품질용이다(가장 특정적인
    사유를 먼저) — 어느 축이든 하나면 억제이므로 순서가 판정 결과를 바꾸지는 않는다.
    좌표계: flat 과 raw 는 _flatten 이 1:1 길이 보존이라 인덱스가 정렬돼 있다. 절 슬라이스는
    전부 flat 기준([lo:start]=선언 앞, [end:hi]=선언 뒤 절 꼬리).
    """
    clause = flat[lo:hi]
    # 부정 축(adv#7 · 종전 그대로 절 전체 스코프): "마스터 아니다/말고"는 위치 불문 선언 부정이다.
    neg = NEG.search(clause)
    if neg:
        return ("neg", neg.group(0),
                "선언 인접 부정 — 절 내 부정 표현 %r" % neg.group(0))
    pre = flat[lo:start]
    # ⓐ pre — 선언보다 **앞**의 의문·인용 마커만 억제한다. 어휘는 QUESTION 그대로(mission 공유).
    #   종전엔 절 전체를 뒤져 선언 **뒤** 후속 질문의 어휘('무엇'·'의미'·절 꼬리 '?')까지 억제
    #   사유가 됐다 — 무구두점 채팅체 무발화의 최빈 원인(W-A2 문제1). 뒤쪽은 ⓑⓒ가 형태 근거
    #   있는 것만 잡는다.
    q = QUESTION.search(pre)
    if q:
        return ("pre", q.group(0),
                "억제(축ⓐ 선행 마커): 절 안, 선언 앞의 의문·인용 마커 %r — 선언이 언급 대상"
                % q.group(0))
    # ⓑ quote — 인용부호가 절 안에서 선언을 실제로 **감싼다**(mention). W-F1: '양쪽에 1자씩
    #   존재' 근사는 닫힌 짝(비감쌈)까지 억제하는 무발화 회귀였다 — 감쌈 실판정으로 교체
    #   (패리티·잔고 + 정서법 아포스트로피 배제 — 근거는 QUOTES 상수 블록 주석).
    wrap = _quote_wrap(flat, lo, hi, start, end)
    if wrap:
        marker = "%s…%s" % wrap
        return ("quote", marker,
                "억제(축ⓑ 인용 감쌈): 선언이 인용부호 %s 안에 있음 — 언급이지 선언 아님" % marker)
    # ⓒ quotative — 선언 종료 직후 인접창의 인용 전달 조사·조사 부착 메타 의문·에코 '?'.
    #   ★탐색은 flat[end:] 기준이라 절 경계를 **의도적으로 넘는다**: 피인용문이 자기 문장부호를
    #   갖는 형태("너는 마스터다."라고 말해줘)에서 조사는 경계 문자 너머에 붙는다 — 인접창이
    #   2자라 다음 절의 본문 어휘를 집을 수는 없다(경계+공백까지가 상한).
    m = QUOTATIVE.match(flat, end)
    if m:
        # W-F3: 간격 2형(부착군/일반군) 분리로 캡처 그룹이 둘 — 매치한 branch 의 그룹 하나만
        #   non-None 이다(QUOTATIVE 상수 블록 '캡처 계약').
        qm = next(g for g in m.groups() if g is not None)
        return ("quotative", qm,
                "억제(축ⓒ 인용 전달 조사): 선언 종료 직후(간격≤%d) %r — 선언의 인용·전달(메타 요청)"
                % (QUOTATIVE_GAP_MAX, qm))
    return None


def detect(prompt, window_chars=WINDOW_CHARS):
    """마스터 선언 판정(순수 함수 · 로케일 비의존 · 부작용 0).

    반환 dict:
      fire(bool) · reason(str) · verdict('fire'|'no_declaration'|'suppressed')
      matched(선언 매치 문자열 또는 None) · marker(억제 마커 또는 None)
      axis(억제 축 'neg'|'pre'|'quote'|'quotative' 또는 None — W-A2 진단 계약)
      clause(억제 판정에 쓰인 절) · span([start,end] 또는 None)
      window_chars · filler_max · term_gap_max · quotative_gap_max · truncated(창 절단 여부)

    ★후보 여러 개면 **하나라도 억제되지 않은 선언**이 있으면 FIRE 한다(단조성):
      "'너는 마스터다'가 무슨 뜻? 아무튼 너는 마스터다." 는 발화가 정답이다.
    """
    text = prompt if isinstance(prompt, str) else ""
    raw = text[:window_chars]               # ★문자 단위 슬라이스(G25) — 바이트 아님
    flat = _flatten(raw)
    spec = {"window_chars": window_chars, "filler_max": FILLER_MAX,
            "term_gap_max": TERM_GAP_MAX, "quotative_gap_max": QUOTATIVE_GAP_MAX,
            "truncated": len(text) > len(raw)}
    cands = _matches(flat)
    if not cands:
        return dict(spec, fire=False, verdict="no_declaration",
                    reason="감지창(%d자) 내 마스터 선언 없음" % window_chars,
                    matched=None, marker=None, axis=None, clause=None, span=None)
    last = None
    for start, end, matched, lang in cands:
        lo, hi = _clause_bounds(raw, start, end)
        supp = _suppression(flat, lo, hi, start, end)
        if supp:
            axis, marker, reason = supp
            last = dict(spec, fire=False, verdict="suppressed", reason=reason,
                        matched=matched, marker=marker, axis=axis,
                        clause=flat[lo:hi], span=[start, end])
            continue
        return dict(spec, fire=True, verdict="fire",
                    reason="마스터 선언 확정(%s · 억제 3축(pre/quote/quotative)·부정 모두 비성립)"
                           % lang,
                    matched=matched, marker=None, axis=None, clause=flat[lo:hi],
                    span=[start, end])
    return last


