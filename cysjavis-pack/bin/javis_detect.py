#   <한글>' 꼴 실재어가 나타나면 오억제(무발화 방향)인데 실측 0 이라 감수한다(발견 시 corpus
#   FIRE 핀 추가 후 해당 음절만 재협착).
# ★기각(억제는 문법 근거가 있을 때만 — W-A2 · 표준어 보조사 전수 처분의 잔여 전부):
#   '은'은 모음('고') 뒤 비문 결합이나 티켓 최소 집합 명시+오철 방어로 채택(어두 실재어 0 =
#   무해) · '뿐'(체언·-ㄹ 관형사형 뒤 결합 — '라고뿐' 비문·용례 0) · '커녕' 단독(항상 '는커녕'
